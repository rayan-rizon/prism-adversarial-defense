"""
P2: Per-attack score distribution histograms (clean vs adversarial).

Reuses the adversarial pools generated by test_recovery_multi_attack.py
(FGSM, Square, CW) on the same VAL-split n inputs, computes ensemble
score for each, and produces a quantitative summary table + a stacked
histogram figure.

Output:
  experiments/stress/results_score_histograms.json
  paper/figures/fig_score_dist_local_val.pdf (4-panel: FGSM/Square/CW/(legend))
"""
import os, sys, time, json, pickle
import numpy as np
import torch
import torchvision.transforms as T
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt

HERE = os.path.dirname(os.path.abspath(__file__))
PRISM_ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
sys.path.insert(0, PRISM_ROOT)

from src import bootstrap  # noqa: F401
from src.tamm.extractor import ActivationExtractor
from src.tamm.tda import TopologicalProfiler
from src.tamm.scorer import TopologicalScorer
from src.tamm.logit_stability import compute_input_stability_features
from src.tamm.persistence_stats import compute_logit_profile_features
from src.cadg.ensemble_scorer import PersistenceEnsembleScorer
from src.attacks.cw_torch import cw_l2_attack_torch
from src.config import (
    LAYER_NAMES, LAYER_WEIGHTS, DIM_WEIGHTS,
    BACKBONE_MEAN, BACKBONE_STD, BACKBONE_NUM_CLASSES, EPS_LINF_STANDARD,
    PATHS, N_SUBSAMPLE, MAX_DIM, VAL_IDX, BACKBONE_INPUT_SIZE,
)
from src.data_loader import load_test_dataset
from src.models import load_backbone

try:
    from art.attacks.evasion import FastGradientMethod, SquareAttack
    from art.estimators.classification import PyTorchClassifier
except ImportError:
    print('ERROR: ART not installed.')
    sys.exit(1)


_PIXEL_TRANSFORM = T.Compose([T.ToTensor()])
_NORMALIZE = T.Normalize(mean=BACKBONE_MEAN, std=BACKBONE_STD)


def score_one(backbone, profiler, extractor, ens, img_pixel, device):
    x_norm = _NORMALIZE(img_pixel).unsqueeze(0).to(device)
    acts = extractor.extract(x_norm)
    dgms = {L: profiler.compute_diagram(acts[L].squeeze(0).cpu().numpy())
            for L in LAYER_NAMES}
    use_grad = getattr(ens, 'use_grad_norm', False)
    use_sm = getattr(ens, 'use_softmax_entropy', False)
    use_lp = getattr(ens, 'use_logit_profile_features', False)
    use_st = getattr(ens, 'use_stability_features', False)
    use_dct = getattr(ens, 'use_dct', False)
    stab_count = int(getattr(ens, 'stability_feature_count', 8) or 8)

    img_np = img_pixel.detach().cpu().numpy() if use_dct else None
    gn = None
    if use_grad:
        x_g = x_norm.detach().clone().requires_grad_(True)
        with torch.enable_grad():
            lg = backbone(x_g)
            pred = int(lg.argmax(1).item())
            (gx,) = torch.autograd.grad(lg[0, pred], x_g)
        gn = float(gx.norm().item())
    logits_np = None
    if use_sm or use_lp or use_st:
        with torch.no_grad():
            logits_np = backbone(x_norm).squeeze(0).cpu().numpy()
    lp = compute_logit_profile_features(logits_np) if use_lp else None
    stab = compute_input_stability_features(
        model=backbone, x_norm=x_norm, img_pixel=img_pixel,
        mean=BACKBONE_MEAN, std=BACKBONE_STD,
        logits_np=logits_np, feature_count=stab_count,
    ) if use_st else None
    return float(ens.score(dgms, image=img_np, grad_norm=gn, logits=logits_np,
                           logit_profile_features=lp, stability_features=stab))


def main():
    n = 80
    seed = 42

    device = 'cuda' if torch.cuda.is_available() else 'cpu'
    print(f'device: {device}')

    backbone = load_backbone(device=device)
    norm_backbone = load_backbone(device=device, wrap=True)
    extractor = ActivationExtractor(backbone, LAYER_NAMES)
    profiler = TopologicalProfiler(n_subsample=N_SUBSAMPLE, max_dim=MAX_DIM)
    with open(PATHS['reference_profiles'], 'rb') as f:
        ref = pickle.load(f)
    base = TopologicalScorer(ref_profiles=ref, layer_names=LAYER_NAMES,
                             layer_weights=LAYER_WEIGHTS, dim_weights=DIM_WEIGHTS)
    ens = PersistenceEnsembleScorer.load(PATHS['ensemble_scorer'], base, LAYER_NAMES)
    with open(PATHS['calibrator'], 'rb') as f:
        calib = pickle.load(f)
    thr = calib.thresholds

    ds = load_test_dataset(root='./data', transform=_PIXEL_TRANSFORM)
    rng = np.random.RandomState(seed)
    pick = sorted(rng.choice(list(range(*VAL_IDX)), n, replace=False).tolist())
    clean_stack = torch.stack([ds[int(i)][0] for i in pick]).to(device)
    print(f'clean batch: {clean_stack.shape}')

    classifier = PyTorchClassifier(
        model=norm_backbone, loss=torch.nn.CrossEntropyLoss(),
        input_shape=(3, BACKBONE_INPUT_SIZE, BACKBONE_INPUT_SIZE),
        nb_classes=BACKBONE_NUM_CLASSES,
        clip_values=(0.0, 1.0),
        device_type='gpu' if device == 'cuda' else 'cpu',
    )

    print('FGSM...')
    fgsm = FastGradientMethod(estimator=classifier, eps=EPS_LINF_STANDARD)
    fgsm_adv = torch.tensor(fgsm.generate(clean_stack.cpu().numpy())).to(device)
    print('Square (max_iter=500)...')
    sq = SquareAttack(estimator=classifier, eps=EPS_LINF_STANDARD,
                      max_iter=500, nb_restarts=1, batch_size=n)
    square_adv = torch.tensor(sq.generate(clean_stack.cpu().numpy())).to(device)
    print('CW (kappa=0)...')
    cw_adv, _ = cw_l2_attack_torch(
        norm_backbone, clean_stack, device,
        max_iter=40, binary_search_steps=5,
        learning_rate=0.01, confidence=0.0, initial_const=0.01,
    )

    print('\nscoring clean + adversarials...')
    clean_scores = np.array([
        score_one(backbone, profiler, extractor, ens, ds[int(i)][0], device)
        for i in pick
    ])
    fgsm_scores = np.array([
        score_one(backbone, profiler, extractor, ens, fgsm_adv[i].cpu(), device)
        for i in range(n)
    ])
    sq_scores = np.array([
        score_one(backbone, profiler, extractor, ens, square_adv[i].cpu(), device)
        for i in range(n)
    ])
    cw_scores = np.array([
        score_one(backbone, profiler, extractor, ens, cw_adv[i].cpu(), device)
        for i in range(n)
    ])

    def summary(name, s):
        return {
            'name': name, 'n': int(s.size),
            'mean': float(s.mean()), 'std': float(s.std()),
            'p5': float(np.percentile(s, 5)), 'p25': float(np.percentile(s, 25)),
            'p50': float(np.percentile(s, 50)), 'p75': float(np.percentile(s, 75)),
            'p95': float(np.percentile(s, 95)),
            'min': float(s.min()), 'max': float(s.max()),
            'TPR_L1': float(np.mean(s > thr['L1'])),
            'TPR_L2': float(np.mean(s > thr['L2'])),
            'TPR_L3': float(np.mean(s > thr['L3'])),
        }

    summaries = [summary(k, v) for k, v in [
        ('clean', clean_scores), ('FGSM', fgsm_scores),
        ('Square', sq_scores), ('CW', cw_scores),
    ]]
    for s in summaries:
        print(f"  {s['name']:>6s}  mean={s['mean']:>6.2f}  std={s['std']:>5.2f}  "
              f"p50={s['p50']:>6.2f}  p95={s['p95']:>6.2f}  "
              f"TPR(L1)={s['TPR_L1']:.3f}")

    out_path = os.path.join(HERE, 'results_score_histograms.json')
    with open(out_path, 'w') as f:
        json.dump({
            'n': n, 'seed': seed, 'split': 'VAL',
            'thresholds': {k: float(v) for k, v in thr.items()},
            'summaries': summaries,
            'raw_scores': {
                'clean': clean_scores.tolist(), 'FGSM': fgsm_scores.tolist(),
                'Square': sq_scores.tolist(), 'CW': cw_scores.tolist(),
            },
        }, f, indent=2)
    print(f'wrote {out_path}')

    # Figure
    fig, axes = plt.subplots(2, 2, figsize=(10, 6))
    palettes = {
        'clean': 'steelblue',
        'FGSM': 'tab:orange',
        'Square': 'tab:green',
        'CW': 'tab:red',
    }
    sets = [
        ('FGSM', fgsm_scores), ('Square', sq_scores),
        ('CW', cw_scores), None,
    ]
    bins = np.linspace(-10, 20, 41)
    for ax, item in zip(axes.flat, sets):
        if item is None:
            ax.axis('off')
            # Legend panel
            for nm, c in palettes.items():
                ax.plot([], [], color=c, label=nm, linewidth=8)
            for tname, tval in thr.items():
                ax.axvline(tval, ls='--', color='k', alpha=0.4,
                           label=f'{tname}={tval:.2f}')
            ax.legend(loc='center', fontsize=10)
            continue
        attack_name, adv_s = item
        ax.hist(clean_scores, bins=bins, color=palettes['clean'],
                alpha=0.6, label='clean', density=True)
        ax.hist(adv_s, bins=bins, color=palettes[attack_name],
                alpha=0.6, label=attack_name, density=True)
        for tname, tval in thr.items():
            ax.axvline(tval, ls='--', color='k', alpha=0.4)
        ax.set_title(f'{attack_name} (TPR L1={(adv_s > thr["L1"]).mean():.2f})')
        ax.set_xlabel('PRISM score')
        ax.set_ylabel('density')
        ax.legend(loc='upper right', fontsize=8)
    plt.tight_layout()
    fig_path = os.path.join(PRISM_ROOT, 'paper', 'figures',
                            'fig_score_hist_local_val.pdf')
    plt.savefig(fig_path)
    print(f'wrote {fig_path}')


if __name__ == '__main__':
    main()
