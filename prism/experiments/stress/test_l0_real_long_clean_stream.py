"""
P0 stress test (REAL scores): bootstrap a long clean stream from the
n=1000 REAL VAL-split clean ensemble scores generated by
compute_real_clean_scores.py. Run the deployed CUSUM L0 monitor on
streams of length {500, 1000, 2000, 5000, 10000} across 5 seeds.

This refines the synthetic Gaussian / bootstrap-from-clean_scores.npy
test (test_l0_long_clean_stream.py) by using actual deployed-pipeline
scores. Heavy-tail behavior is captured exactly.

Source scores: experiments/stress/real_clean_scores_val_n1000.npy
  (mean ~ 0.17, std ~ 2.05 — matches pkl score_center=0.281, score_scale=1.639)
"""
import os, sys, json, pickle
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
PRISM_ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
sys.path.insert(0, PRISM_ROOT)
from src.sacd.monitor import CampaignMonitor

PKL_PATH = os.path.join(PRISM_ROOT, 'models', 'l0_thresholds.pkl')
REAL_SCORES = os.path.join(HERE, 'real_clean_scores_val_n1000.npy')

SEEDS = [42, 123, 456, 789, 999]
STREAM_LENS = [500, 1000, 2000, 5000, 10000]
THRESHOLDS = [5.0, 8.0, 10.0, 12.0]


def make_monitor(pkl, thr):
    return CampaignMonitor(
        hazard_rate=pkl['hazard_rate'],
        alert_run_prob=pkl['alert_run_prob'],
        warmup_steps=pkl['warmup_steps'],
        l0_factor=pkl['l0_factor'],
        detection_mode=pkl['detection_mode'],
        score_center=pkl['score_center'],
        score_scale=pkl['score_scale'],
        cusum_drift=pkl['cusum_drift'],
        cusum_threshold=thr,
        cusum_k_consecutive=pkl['cusum_k_consecutive'],
    )


def run_stream(monitor, scores):
    n_active = 0
    first = None
    for i, s in enumerate(scores):
        st = monitor.process_score(float(s))
        if st['l0_active']:
            n_active += 1
            if first is None:
                first = i
    return n_active, first


def main():
    pkl = pickle.load(open(PKL_PATH, 'rb'))
    real = np.load(REAL_SCORES).astype(np.float64)
    print(f'Real VAL clean pool: n={len(real)}, mean={real.mean():.4f}, '
          f'std={real.std():.4f}, min={real.min():.4f}, max={real.max():.4f}')
    print(f'  (pkl score_center={pkl["score_center"]:.4f}, '
          f'score_scale={pkl["score_scale"]:.4f})')
    print()

    out = {
        'real_scores_source': REAL_SCORES,
        'real_pool_stats': {
            'n': int(real.size), 'mean': float(real.mean()),
            'std': float(real.std()), 'min': float(real.min()),
            'max': float(real.max()),
            'p95': float(np.percentile(real, 95)),
            'p99': float(np.percentile(real, 99)),
        },
        'pkl_values': {k: pkl[k] for k in (
            'detection_mode','cusum_drift','cusum_threshold','warmup_steps',
            'cusum_k_consecutive','score_center','score_scale','alert_run_prob',
            'hazard_rate','l0_factor','alert_run_length',
        )},
        'thresholds': THRESHOLDS,
        'results': [],
    }

    for thr in THRESHOLDS:
        for L in STREAM_LENS:
            per_seed = []
            trigs = []
            for sd in SEEDS:
                rng = np.random.default_rng(sd)
                stream = rng.choice(real, size=L, replace=True)
                mon = make_monitor(pkl, thr)
                n_active, first = run_stream(mon, stream)
                per_seed.append(n_active / L)
                trigs.append(first)
            mean_f = float(np.mean(per_seed))
            max_f = float(np.max(per_seed))
            n_tr = sum(t is not None for t in trigs)
            out['results'].append({
                'threshold': thr, 'length': L,
                'per_seed_fraction': per_seed,
                'mean_fraction': mean_f, 'max_fraction': max_f,
                'seeds_with_trigger': n_tr, 'first_triggers': trigs,
            })
            mark = '  ' if mean_f < 0.001 else '!!'
            print(f'{mark} thr={thr:>5.1f}  L={L:>5d}  '
                  f'mean={mean_f:.5f}  max={max_f:.5f}  '
                  f'n_trig={n_tr}/5  first={trigs}')
        print()

    out_path = os.path.join(HERE, 'results_l0_real_long_clean_stream.json')
    with open(out_path, 'w') as f:
        json.dump(out, f, indent=2, default=str)
    print('wrote', out_path)


if __name__ == '__main__':
    main()
